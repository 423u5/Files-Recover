"""Writes tests/support/document_samples.cpp from a folder of documents made by
tests/reference/make_document_samples.ps1 and make_document_samples.sh.

Runs of 64 or more zero bytes are left out (the samples' pieces are what lies
between them): compound files are mostly empty sectors.

Usage: python3 embed_document_samples.py <output .cpp> <folder>
"""

import os
import re
import sys

FORMATS = {".pdf": "pdf", ".doc": "ole2", ".xls": "ole2", ".msi": "ole2", ".oxps": "zip"}
PRODUCERS = {
    "edge": "Microsoft Edge 155 (Skia/PDF m155)",
    "mspdf": "Microsoft Print to PDF (Windows 10 22H2)",
    "xps": "Microsoft XPS Document Writer v4 (Windows 10 22H2)",
    "stg": "Windows structured storage (StgCreateStorageEx, Windows 10 22H2)",
    "wi": "Windows Installer 5.0 (WindowsInstaller.Installer)",
    "qpdf": "qpdf 11.9.0",
}
MAX_SAMPLE = 32 * 1024
ZERO_RUN = 64

out_path, folder = sys.argv[1], sys.argv[2]
files = []
for name in sorted(os.listdir(folder)):
    stem, ext = os.path.splitext(name)
    if ext not in FORMATS:
        continue
    with open(os.path.join(folder, name), "rb") as f:
        data = f.read()
    if len(data) > MAX_SAMPLE:
        sys.exit(f"{name} is larger than {MAX_SAMPLE} bytes; samples must stay small")
    pieces = []
    at = 0
    for run in re.finditer(rb"\x00{%d,}" % ZERO_RUN, data):
        if run.start() > at:
            pieces.append((at, data[at:run.start()]))
        at = run.end()
    if at < len(data):
        pieces.append((at, data[at:]))
    files.append((name, FORMATS[ext], PRODUCERS[stem.split("_")[0]], len(data), pieces))

lines = [
    "// Generated by tests/reference/embed_document_samples.py from the output of",
    "// tests/reference/make_document_samples.ps1 and make_document_samples.sh. Do not edit.",
    "",
    '#include "support/document_samples.hpp"',
    "",
    "#include <array>",
    "#include <cstdlib>",
    "",
    "namespace recovery::test::document_samples {",
    "",
    "namespace {",
    "",
]
for index, (name, _, _, size, pieces) in enumerate(files):
    lines.append(f"// {name}: {size} bytes, {len(pieces)} piece{'' if len(pieces) == 1 else 's'}")
    for p, (offset, data) in enumerate(pieces):
        lines.append(f"constexpr std::array<std::uint8_t, {len(data)}> kSample{index}Piece{p} = {{")
        for start in range(0, len(data), 24):
            chunk = ", ".join(f"0x{b:02X}" for b in data[start:start + 24])
            lines.append(f"    {chunk},")
        lines.append("};")
    lines.append(f"const std::array<Piece, {len(pieces)}> kSample{index} = {{{{")
    for p, (offset, _) in enumerate(pieces):
        lines.append(f"    {{{offset}, kSample{index}Piece{p}}},")
    lines.append("}};")
    lines.append("")
lines.append("}  // namespace")
lines.append("")
lines.append("const std::vector<Sample>& all() {")
lines.append("    static const std::vector<Sample> samples = {")
for index, (name, fmt, producer, size, _) in enumerate(files):
    lines.append(f'        {{"{name}", "{fmt}", "{producer}", {size}, kSample{index}}},')
lines.append("    };")
lines.append("    return samples;")
lines.append("}")
lines.append("")
lines.append("const Sample& named(std::string_view name) {")
lines.append("    for (const Sample& sample : all()) {")
lines.append("        if (sample.name == name) {")
lines.append("            return sample;")
lines.append("        }")
lines.append("    }")
lines.append("    std::abort();")
lines.append("}")
lines.append("")
lines.append("}  // namespace recovery::test::document_samples")
with open(out_path, "w", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print(f"wrote {len(files)} samples to {out_path}")
